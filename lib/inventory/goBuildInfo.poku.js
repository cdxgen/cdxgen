import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { assert, describe, it } from "poku";

import {
  PRE_1_18_VERSION,
  parseGoBuildModuleSettings,
  readGoBuildSettings,
  readGoBuildVersion,
} from "./goBuildInfo.js";

function hasGo() {
  try {
    execFileSync("go", ["version"], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

// Writes a buffer that follows debug/buildinfo's own layout for the inline
// (go1.18+) format: magic, pointer size, flags, a 16-byte reserved slot,
// then a uvarint length and the version bytes. Generated by a Go program so
// the bytes come from the format's owner, not from re-implementing it here.
const BUILDINF_WRITER = `package main

import (
	"os"
)

func main() {
	version := os.Args[1]
	out := make([]byte, 32)
	copy(out, []byte("\\xff Go buildinf:"))
	out[14] = 8  // ptrSize
	out[15] = 2  // flagInlineBuildInfo
	os.Stdout.Write(out[:32])
	os.Stdout.Write([]byte{byte(len(version))})
	os.Stdout.Write([]byte(version))
}
`;

describe("readGoBuildVersion()", () => {
  it("reads the toolchain version from a real Go binary", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-"));
    try {
      writeFileSync(join(work, "main.go"), "package main\n\nfunc main() {}\n");
      writeFileSync(
        join(work, "go.mod"),
        "module example.test/hello\n\ngo 1.22\n",
      );
      const binary = join(work, "hello");
      execFileSync("go", ["build", "-o", binary, "."], {
        cwd: work,
        env: {
          ...process.env,
          CGO_ENABLED: "0",
          GOOS: "linux",
          GOARCH: "amd64",
        },
      });
      const goVersion = execFileSync("go", ["version"], { encoding: "utf-8" })
        .split(" ")[2]
        .replace(/^go/, "");
      const version = readGoBuildVersion(binary);
      assert.match(version, /^go\d+\.\d+/);
      assert.ok(
        version === `go${goVersion}` || version.startsWith("go"),
        `read ${version}`,
      );
      // The version matches the local toolchain exactly when no toolchain
      // directive redirected the build.
      assert.strictEqual(
        version,
        execFileSync("go", ["version"], { encoding: "utf-8" }).split(" ")[2],
      );
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("parses a header buffer generated from debug/buildinfo's layout", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-gen-"));
    try {
      writeFileSync(join(work, "gen.go"), BUILDINF_WRITER);
      const header = execFileSync("go", ["run", "gen.go", "go9.9.9"], {
        cwd: work,
      });
      const bufferPath = join(work, "header.bin");
      writeFileSync(bufferPath, header);
      assert.strictEqual(readGoBuildVersion(bufferPath), "go9.9.9");
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("reports pre-1.18 layouts without following pointers", () => {
    const header = Buffer.alloc(64);
    header.set(
      [
        0xff, 0x20, 0x47, 0x6f, 0x20, 0x62, 0x75, 0x69, 0x6c, 0x64, 0x69, 0x6e,
        0x66, 0x3a,
      ],
      0,
    );
    header[14] = 8;
    header[15] = 0; // no inline version: old pointer-based layout
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-old-"));
    try {
      const path = join(work, "old.bin");
      writeFileSync(path, header);
      assert.strictEqual(readGoBuildVersion(path), PRE_1_18_VERSION);
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("returns undefined for non-Go files and garbage", () => {
    assert.strictEqual(
      readGoBuildVersion(join("lib", "inventory", "goBuildInfo.js")),
      undefined,
    );
    assert.strictEqual(readGoBuildVersion("/nonexistent/binary"), undefined);
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-garbage-"));
    try {
      const path = join(work, "garbage.bin");
      writeFileSync(path, Buffer.alloc(4096, 0x41));
      assert.strictEqual(readGoBuildVersion(path), undefined);
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("handles a magic deep inside the file (chunked search)", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    // The magic can sit megabytes into a real binary; place it past one
    // 64 KiB chunk to prove the aligned chunked search finds it.
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-deep-"));
    try {
      writeFileSync(join(work, "gen.go"), BUILDINF_WRITER);
      const header = execFileSync("go", ["run", "gen.go", "go8.8.8"], {
        cwd: work,
      });
      const buffer = Buffer.concat([Buffer.alloc(200000, 0), header]);
      const path = join(work, "deep.bin");
      writeFileSync(path, buffer);
      assert.strictEqual(readGoBuildVersion(path), "go8.8.8");
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });
});

describe("readGoBuildVersion() chunk-boundary regressions", () => {
  it("finds headers in every aligned slot around chunk boundaries", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-slots-"));
    try {
      writeFileSync(join(work, "gen.go"), BUILDINF_WRITER);
      const header = execFileSync("go", ["run", "gen.go", "go6.6.6"], {
        cwd: work,
      });
      for (const offset of [
        65504,
        65520,
        65536,
        65552,
        65744,
        131056,
        196592,
        70 * 1024 * 1024,
      ]) {
        const buffer = Buffer.concat([Buffer.alloc(offset, 0), header]);
        const path = join(work, "slot.bin");
        writeFileSync(path, buffer);
        assert.strictEqual(
          readGoBuildVersion(path),
          "go6.6.6",
          `header at aligned offset ${offset} must be found`,
        );
      }
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("never decodes a version from bytes outside the current read", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-stale-"));
    try {
      writeFileSync(join(work, "gen.go"), BUILDINF_WRITER);
      const header = execFileSync("go", ["run", "gen.go", "go5.5.5"], {
        cwd: work,
      });
      // A payload-shaped decoy early in the file and a header truncated
      // mid-version near EOF: the truncated header must not read the decoy.
      const attack = Buffer.alloc(65590, 0);
      attack.set(header.subarray(32), 48);
      attack.set(header.subarray(0, 36), 65552);
      const path = join(work, "attack.bin");
      writeFileSync(path, attack);
      assert.strictEqual(readGoBuildVersion(path), undefined);
      // The same header complete at the same offset is found.
      const clean = Buffer.alloc(65600, 0);
      clean.set(header, 65552);
      writeFileSync(path, clean);
      assert.strictEqual(readGoBuildVersion(path), "go5.5.5");
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });
});

// Builds a module-info string the way the linker writes it: the 16-byte
// sentinels of cmd/go/internal/modload around the `go version -m`-style
// records, each record newline-terminated, so parseGoBuildModuleSettings
// sees real framing.
function framedModuleInfo(lines) {
  const start = Buffer.from("3077af0c9274080241e1c107e6d618e6", "hex").toString(
    "latin1",
  );
  const end = Buffer.from("f932433186182072008242104116d8f2", "hex").toString(
    "latin1",
  );
  return `${start}${lines.join("\n")}\n${end}`;
}

describe("readGoBuildSettings()", () => {
  it("reads cgo, trimpath and buildmode from a real cgo binary", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    const cxx = (() => {
      for (const candidate of ["cc", "gcc", "clang"]) {
        try {
          execFileSync(candidate, ["--version"], { stdio: "ignore" });
          return candidate;
        } catch {
          // try the next
        }
      }
      return undefined;
    })();
    if (!cxx) {
      console.log("skip: no C compiler for a cgo build");
      return;
    }
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-cgo-"));
    try {
      writeFileSync(
        join(work, "main.go"),
        'package main\n\n/*\n#cgo CFLAGS: -DCGO_PROBE=1\n#include <stdlib.h>\n*/\nimport "C"\nimport "fmt"\n\nfunc main() { fmt.Println(C.int(3)) }\n',
      );
      writeFileSync(
        join(work, "go.mod"),
        "module example.test/cgohello\n\ngo 1.22\n",
      );
      const binary = join(work, "cgohello");
      execFileSync("go", ["build", "-o", binary, "."], {
        cwd: work,
        env: {
          ...process.env,
          CGO_ENABLED: "1",
          CC: cxx,
          CGO_CFLAGS: "-DGOBUILDINFO_PROBE=1",
        },
      });
      const settings = readGoBuildSettings(binary);
      assert.ok(settings, "a cgo binary carries buildinfo");
      assert.match(settings.buildVersion, /^go\d+\.\d+/);
      assert.strictEqual(settings.cgoEnabled, true);
      assert.ok(
        settings.cgoEnvFlagNames.includes("CGO_CFLAGS"),
        `flag names: ${settings.cgoEnvFlagNames}`,
      );
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("records cgo disabled and no flag names for a CGO_ENABLED=0 build", () => {
    if (!hasGo()) {
      console.log("skip: go toolchain not available");
      return;
    }
    const work = mkdtempSync(join(tmpdir(), "cdxgen-gobuildinfo-nocgo-"));
    try {
      writeFileSync(join(work, "main.go"), "package main\n\nfunc main() {}\n");
      writeFileSync(
        join(work, "go.mod"),
        "module example.test/plain\n\ngo 1.22\n",
      );
      const binary = join(work, "plain");
      execFileSync("go", ["build", "-o", binary, "."], {
        cwd: work,
        env: {
          ...process.env,
          CGO_ENABLED: "0",
          GOOS: "linux",
          GOARCH: "amd64",
        },
      });
      const settings = readGoBuildSettings(binary);
      assert.ok(settings);
      assert.strictEqual(settings.cgoEnabled, false);
      assert.deepStrictEqual(settings.cgoEnvFlagNames, []);
      assert.strictEqual(settings.trimpath, false);
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  });

  it("parses build settings out of framed module info", () => {
    const moduleInfo = framedModuleInfo([
      "path\texample.test/app",
      "mod\texample.test/app\tv0.0.0",
      "dep\tgithub.com/x/y\tv1.2.3\th1:abc=",
      "build\tCGO_ENABLED=1",
      "build\tGOOS=linux",
      "build\t-buildmode=exe",
      'build\t-ldflags="-s -w"',
      "build\tCGO_CPPFLAGS=",
      "build\tCGO_CFLAGS=-I/opt/include",
      "build\tCGO_LDFLAGS=-Wl,--sysroot=/opt/sys",
    ]);
    const settings = parseGoBuildModuleSettings(moduleInfo);
    assert.strictEqual(settings.cgoEnabled, true);
    assert.strictEqual(settings.buildmode, "exe");
    assert.deepStrictEqual(settings.cgoEnvFlagNames, [
      "CGO_CFLAGS",
      "CGO_LDFLAGS",
    ]);
    assert.strictEqual(settings.trimpath, false);
    // No value ever leaves the parser's result shape.
    assert.ok(!JSON.stringify(settings).includes("/opt/include"));
    assert.ok(!JSON.stringify(settings).includes("--sysroot"));
  });

  it("keeps only the build modes the go command accepts", () => {
    const modeOf = (line) =>
      parseGoBuildModuleSettings(
        framedModuleInfo(["path\texample.test/app", line]),
      ).buildmode;
    assert.strictEqual(modeOf("build\t-buildmode=pie"), "pie");
    assert.strictEqual(modeOf("build\t-buildmode=c-shared"), "c-shared");
    assert.strictEqual(
      modeOf("build\t-buildmode=exe token=ghp_secretvalue"),
      undefined,
      "free text from the binary is not copied into the BOM",
    );
  });

  it("treats an unframed or short module info as no settings", () => {
    assert.deepStrictEqual(parseGoBuildModuleSettings(undefined), {
      cgoEnabled: undefined,
      cgoEnvFlagNames: [],
      trimpath: false,
      buildmode: undefined,
    });
    assert.deepStrictEqual(
      parseGoBuildModuleSettings("build\tCGO_ENABLED=1").cgoEnabled,
      undefined,
      "unframed text has no sentinels to strip and reads as nothing",
    );
  });
});
