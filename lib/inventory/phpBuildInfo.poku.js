const MARKER = "X-Powered-By: PHP/";
const CHUNK = 1024 * 1024;
const CAP = 256 * 1024 * 1024;

function withWork(fn) {
  const work = mkdtempSync(join(tmpdir(), "cdxgen-phpbuildinfo-"));
  try {
    return fn(work);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

// Synthetic file: a bounded byte pattern with the php-src marker and a
// terminator byte, so the version boundary is fixed regardless of what the
// pattern holds.
function binaryWithMarker(version, { offset = 0, size } = {}) {
  const body = Buffer.from(`${MARKER}${version}\0`);
  const length = size || offset + body.length + 64;
  const buffer = Buffer.alloc(length, 0x41);
  body.copy(buffer, offset);
  return buffer;
}

function headerFile(work, prefix, version) {
  const dir = join(work, prefix, "include", "php", "main");
  mkdirSync(dir, { recursive: true });
  const header = join(dir, "php_version.h");
  writeFileSync(
    header,
    [
      "/* automatically generated by configure */",
      "#define PHP_MAJOR_VERSION 8",
      "#define PHP_MINOR_VERSION 4",
      `#define PHP_VERSION "${version}"`,
      "#define PHP_VERSION_ID 80400",
      "",
    ].join("\n"),
  );
  return header;
}

describe("classifyPhpSapi()", () => {
  it("recognises every name php-src installs, versioned or not", () => {
    const cases = {
      php: "cli",
      php8: "cli",
      "php8.4": "cli",
      "php-fpm": "fpm",
      "php-fpm8.4": "fpm",
      "php-cgi": "cgi",
      "php-cgi8.4": "cgi",
      phpdbg: "phpdbg",
      "phpdbg8.4": "phpdbg",
      "libphp.so": "libphp",
      "libphp8.4.so": "libphp",
      "libphp7.so": "libphp",
      frankenphp: "frankenphp",
    };
    for (const [name, sapi] of Object.entries(cases)) {
      assert.strictEqual(classifyPhpSapi(name), sapi, name);
      assert.strictEqual(classifyPhpSapi(`/usr/local/bin/${name}`), sapi, name);
    }
  });

  it("rejects names that are not PHP runtime files", () => {
    for (const name of [
      "php-config",
      "phpize",
      "php.ini",
      "php-fpm.conf",
      "libphp.so.bak",
      "libphp.a",
      "PHP",
      "php-cgi.bak",
      "frankenphp-worker",
      "",
    ]) {
      assert.strictEqual(classifyPhpSapi(name), undefined, name);
    }
  });
});

describe("readPhpBuildVersion()", () => {
  it("finds the marker inside random bytes", () =>
    withWork((work) => {
      const file = join(work, "php");
      const buffer = randomBytes(8192);
      Buffer.from(`${MARKER}8.4.26\0`).copy(buffer, 1234);
      writeFileSync(file, buffer);
      assert.deepStrictEqual(readPhpBuildVersion(file), {
        version: "8.4.26",
        source: "binary",
      });
    }));

  it("returns undefined when the marker is absent", () =>
    withWork((work) => {
      const file = join(work, "php");
      writeFileSync(file, randomBytes(4096));
      assert.strictEqual(readPhpBuildVersion(file), undefined);
    }));

  it("finds a marker split across the 1 MiB read boundary", () =>
    withWork((work) => {
      const file = join(work, "php");
      for (const offset of [CHUNK - 18, CHUNK - 5, CHUNK - 1, CHUNK]) {
        writeFileSync(file, binaryWithMarker("8.4.26", { offset }));
        assert.strictEqual(
          readPhpBuildVersion(file)?.version,
          "8.4.26",
          `marker at ${offset}`,
        );
      }
    }));

  it("finds a marker in a final read shorter than one window", () =>
    withWork((work) => {
      // The file ends within one overlap of the 1 MiB edge, so the marker
      // after the edge is only ever in the first, and last, read.
      const file = join(work, "php");
      for (const offset of [CHUNK, CHUNK + 2]) {
        const body = `${MARKER}8.4.26\0`;
        writeFileSync(
          file,
          binaryWithMarker("8.4.26", { offset, size: offset + body.length }),
        );
        assert.strictEqual(
          readPhpBuildVersion(file)?.version,
          "8.4.26",
          `marker at ${offset} in a file of ${offset + body.length} bytes`,
        );
      }
    }));

  it("does not read a marker past the 256 MiB cap", () =>
    withWork((work) => {
      const file = join(work, "php");
      const fd = openSync(file, "w");
      try {
        ftruncateSync(fd, CAP + 4 * 1024 * 1024);
        const body = Buffer.from(`${MARKER}8.4.26\0`);
        writeSync(fd, body, 0, body.length, CAP + 1024 * 1024);
        // A marker inside the first 256 MiB does not save the file either:
        // the contract gives a file larger than the cap no property.
        writeSync(fd, body, 0, body.length, 1024);
      } finally {
        closeSync(fd);
      }
      assert.strictEqual(readPhpBuildVersion(file), undefined);
      truncateSync(file, 0);
    }));

  it("falls back to php_version.h only when the binary marker is absent", () =>
    withWork((work) => {
      const root = join(work, "root");
      const bin = join(root, "usr", "local", "bin");
      mkdirSync(bin, { recursive: true });
      const file = join(bin, "php");
      writeFileSync(file, Buffer.alloc(2048, 0));
      headerFile(root, "usr/local", "8.4.26");
      assert.deepStrictEqual(readPhpBuildVersion(file, root), {
        version: "8.4.26",
        source: "php_version.h",
      });
    }));

  it("prefers the binary marker over a different header", () =>
    withWork((work) => {
      const root = join(work, "root");
      const bin = join(root, "usr", "local", "bin");
      mkdirSync(bin, { recursive: true });
      const file = join(bin, "php");
      writeFileSync(file, binaryWithMarker("8.4.26"));
      headerFile(root, "usr/local", "8.5.0");
      assert.deepStrictEqual(readPhpBuildVersion(file, root), {
        version: "8.4.26",
        source: "binary",
      });
    }));

  it("does not use php_version.h for a file outside bin/sbin/lib", () =>
    withWork((work) => {
      const root = join(work, "root");
      const share = join(root, "usr", "local", "share", "php");
      mkdirSync(share, { recursive: true });
      const file = join(share, "php");
      writeFileSync(file, Buffer.alloc(2048, 0));
      headerFile(root, "usr/local", "8.4.26");
      assert.strictEqual(readPhpBuildVersion(file, root), undefined);
    }));

  it("returns undefined for an empty file and a truncated header", () =>
    withWork((work) => {
      const root = join(work, "root");
      const bin = join(root, "usr", "local", "bin");
      mkdirSync(bin, { recursive: true });
      const empty = join(bin, "php");
      writeFileSync(empty, "");
      assert.strictEqual(readPhpBuildVersion(empty, root), undefined);

      const file = join(bin, "php-fpm");
      writeFileSync(file, Buffer.alloc(2048, 0));
      const dir = join(root, "usr", "local", "include", "php", "main");
      mkdirSync(dir, { recursive: true });
      writeFileSync(join(dir, "php_version.h"), '#define PHP_VERSION "8.4.2');
      assert.strictEqual(readPhpBuildVersion(file, root), undefined);
    }));

  it("rejects a symlink, including one inside the root", () =>
    withWork((work) => {
      const root = join(work, "root");
      const bin = join(root, "usr", "local", "bin");
      mkdirSync(bin, { recursive: true });
      const outside = join(work, "outside-php");
      writeFileSync(outside, binaryWithMarker("8.4.26"));
      const outsideLink = join(bin, "php");
      symlinkSync(outside, outsideLink);
      assert.strictEqual(readPhpBuildVersion(outsideLink, root), undefined);

      const real = join(bin, "php-real");
      writeFileSync(real, binaryWithMarker("8.4.26"));
      const insideLink = join(bin, "php-fpm");
      symlinkSync(real, insideLink);
      assert.strictEqual(readPhpBuildVersion(insideLink, root), undefined);
      // The target itself is a regular file and is read.
      assert.strictEqual(readPhpBuildVersion(real, root)?.version, "8.4.26");
    }));

  it("rejects a path that resolves outside the root", () =>
    withWork((work) => {
      const root = join(work, "root");
      mkdirSync(root, { recursive: true });
      const outside = join(work, "outside-php");
      writeFileSync(outside, binaryWithMarker("8.4.26"));
      assert.strictEqual(readPhpBuildVersion(outside, root), undefined);
    }));

  it("rejects a FIFO without opening it", () =>
    withWork((work) => {
      if (process.platform === "win32") {
        console.log("skip: FIFO test needs mkfifo");
        return;
      }
      const file = join(work, "php");
      execFileSync("mkfifo", [file]);
      assert.strictEqual(readPhpBuildVersion(file, work), undefined);
    }));

  it("accepts every version shape and rejects malformed ones", () =>
    withWork((work) => {
      const file = join(work, "php");
      for (const version of [
        "8.4.26",
        "8.5.0-dev",
        "8.6.0RC3",
        "8.6.0alpha1",
        "7.4.33",
      ]) {
        writeFileSync(file, binaryWithMarker(version));
        assert.strictEqual(
          readPhpBuildVersion(file)?.version,
          version,
          version,
        );
      }
      for (const version of ["8.4", "8.4.26.1", "v8.4.26"]) {
        writeFileSync(file, binaryWithMarker(version));
        assert.strictEqual(readPhpBuildVersion(file), undefined, version);
      }
    }));
});

describe("parsePhpVersion()", () => {
  it("reads the version a text starts with", () => {
    const cases = {
      "8.4.27": "8.4.27",
      "8.5.0-dev": "8.5.0-dev",
      "8.6.0RC3": "8.6.0RC3",
      "8.6.0alpha1": "8.6.0alpha1",
      "8.6.0beta12": "8.6.0beta12",
      "7.4.33\n": "7.4.33",
      // What follows a version in `php -v`: a space, then the SAPI.
      "8.5.11 (cli) (built: Sep 22 2026 13:32:06) (NTS)": "8.5.11",
      "8.4.27)": "8.4.27",
    };
    for (const [text, version] of Object.entries(cases)) {
      assert.strictEqual(parsePhpVersion(text), version, JSON.stringify(text));
    }
  });

  it("rejects what the build-version grammar rejects", () => {
    for (const text of [
      "8.4",
      "8.4.26.1",
      "8.4.26foo",
      "v8.4.26",
      " 8.4.26",
      "8.6.0RC",
      "8.6.0RC3-dev",
      // A distro revision is not part of the upstream version.
      "8.1.2-1ubuntu2.14 (cli)",
      "7.4.3-4ubuntu2.19",
      `1.${"2".repeat(40)}.3`,
      "",
      undefined,
      null,
      8.4,
    ]) {
      assert.strictEqual(
        parsePhpVersion(text),
        undefined,
        JSON.stringify(text),
      );
    }
  });
});

describe("PHP runtime components", () => {
  it("names the runtime with a generic purl and a CPE", () => {
    assert.strictEqual(phpRuntimeRef("8.4.27"), "pkg:generic/php@8.4.27");
    assert.strictEqual(
      phpCpe("8.4.27"),
      "cpe:2.3:a:php:php:8.4.27:*:*:*:*:*:*:*",
    );
    assert.deepStrictEqual(createPhpRuntimeComponent("8.4.27"), {
      "bom-ref": "pkg:generic/php@8.4.27",
      type: "platform",
      name: "php",
      version: "8.4.27",
      purl: "pkg:generic/php@8.4.27",
      cpe: "cpe:2.3:a:php:php:8.4.27:*:*:*:*:*:*:*",
    });
  });

  it("puts a pre-release in the CPE update field, as NVD does", () => {
    assert.strictEqual(
      phpCpe("8.6.0RC3"),
      "cpe:2.3:a:php:php:8.6.0:rc3:*:*:*:*:*:*",
    );
    assert.strictEqual(
      phpCpe("8.6.0alpha1"),
      "cpe:2.3:a:php:php:8.6.0:alpha1:*:*:*:*:*:*",
    );
    assert.strictEqual(
      phpCpe("8.6.0beta2"),
      "cpe:2.3:a:php:php:8.6.0:beta2:*:*:*:*:*:*",
    );
    assert.strictEqual(
      phpCpe("8.5.0-dev"),
      "cpe:2.3:a:php:php:8.5.0:dev:*:*:*:*:*:*",
    );
    assert.strictEqual(
      createPhpRuntimeComponent("8.6.0RC3").purl,
      "pkg:generic/php@8.6.0RC3",
    );
  });

  it("tags a file with the build facts and links it to one runtime per version", () => {
    const inventory = createPhpRuntimeInventory();
    const files = ["php", "php-fpm", "libphp.so", "php8.6"].map((name) => ({
      "bom-ref": `pkg:generic/${name}`,
      name,
      type: "file",
      properties: [
        { name: "internal:SrcFile", value: `/usr/local/bin/${name}` },
      ],
    }));
    attachPhpBuild(
      inventory,
      files[0],
      { version: "8.4.27", source: "binary" },
      "cli",
    );
    attachPhpBuild(
      inventory,
      files[1],
      { version: "8.4.27", source: "binary" },
      "fpm",
    );
    attachPhpBuild(
      inventory,
      files[2],
      { version: "8.4.27", source: "php_version.h" },
      "libphp",
    );
    attachPhpBuild(
      inventory,
      files[3],
      { version: "8.6.0RC3", source: "binary" },
      "cli",
    );
    assert.deepStrictEqual(files[2].properties, [
      { name: "internal:SrcFile", value: "/usr/local/bin/libphp.so" },
      ...phpBuildProperties(
        { version: "8.4.27", source: "php_version.h" },
        "libphp",
      ),
    ]);
    assert.deepStrictEqual(
      phpBuildProperties({ version: "8.4.27", source: "binary" }, "cli"),
      [
        { name: "cdx:php:buildVersion", value: "8.4.27" },
        { name: "cdx:php:buildVersionSource", value: "binary" },
        { name: "cdx:php:sapi", value: "cli" },
      ],
    );
    assert.deepStrictEqual(
      inventory.runtimeComponents.map((component) => component.purl),
      ["pkg:generic/php@8.4.27", "pkg:generic/php@8.6.0RC3"],
    );
    assert.deepStrictEqual(inventory.dependencies, [
      { ref: "pkg:generic/php@8.4.27", dependsOn: [] },
      { ref: "pkg:generic/php", dependsOn: ["pkg:generic/php@8.4.27"] },
      { ref: "pkg:generic/php-fpm", dependsOn: ["pkg:generic/php@8.4.27"] },
      { ref: "pkg:generic/libphp.so", dependsOn: ["pkg:generic/php@8.4.27"] },
      { ref: "pkg:generic/php@8.6.0RC3", dependsOn: [] },
      { ref: "pkg:generic/php8.6", dependsOn: ["pkg:generic/php@8.6.0RC3"] },
    ]);
  });

  it("caps the files one scan reads at 64", () => {
    assert.strictEqual(MAX_PHP_PROBES, 64);
  });

  it("leaves the CPE out for a version with a distro revision", () => {
    assert.deepStrictEqual(
      createPhpRuntimeComponent("8.1.2-1ubuntu2.14", { withCpe: false }),
      {
        type: "platform",
        name: "php",
        version: "8.1.2-1ubuntu2.14",
        purl: "pkg:generic/php@8.1.2-1ubuntu2.14",
        "bom-ref": "pkg:generic/php@8.1.2-1ubuntu2.14",
      },
    );
  });
});

describe("parsePhpReportedVersion()", () => {
  it("reads an upstream version as parsePhpVersion does", () => {
    for (const [text, version] of [
      ["8.4.27 (cli)", "8.4.27"],
      ["8.5.0-dev (cli)", "8.5.0-dev"],
      ["8.6.0RC3 (cli)", "8.6.0RC3"],
    ]) {
      assert.deepStrictEqual(parsePhpReportedVersion(text), {
        version,
        distroRevision: false,
      });
    }
  });

  it("keeps a distro revision whole and marks it", () => {
    for (const [text, version] of [
      ["8.1.2-1ubuntu2.14 (cli)", "8.1.2-1ubuntu2.14"],
      [
        "8.3.12-1+ubuntu22.04.1+deb.sury.org+1 (cli)",
        "8.3.12-1+ubuntu22.04.1+deb.sury.org+1",
      ],
      ["8.2.29-1~deb12u1", "8.2.29-1~deb12u1"],
    ]) {
      assert.deepStrictEqual(parsePhpReportedVersion(text), {
        version,
        distroRevision: true,
      });
    }
  });

  it("rejects what is neither, and a revision past 64 characters", () => {
    for (const text of [
      undefined,
      "",
      "8.5.11.1 (cli)",
      "8.4.27- (cli)",
      "8.4.27-ubuntu",
      `8.4.27-1${"x".repeat(64)}`,
    ]) {
      assert.strictEqual(parsePhpReportedVersion(text), undefined, `${text}`);
    }
  });
});

describe("packageStoreOf()", () => {
  it("names the package manager whose store a path is in", () => {
    for (const [path, store] of [
      ["/opt/homebrew/Cellar/php/8.5.11_1/bin/php", "homebrew"],
      ["/home/linuxbrew/.linuxbrew/Cellar/php/8.4.27/sbin/php-fpm", "homebrew"],
      ["/nix/store/0abc-php-8.4.27/bin/php", "nix"],
      ["nix/store/0abc-php-8.4.27/bin/php", "nix"],
      ["/gnu/store/0abc-php-8.4.27/bin/php", "guix"],
      ["C:\\nix\\store\\0abc-php\\php.exe", "nix"],
    ]) {
      assert.strictEqual(packageStoreOf(path), store, path);
    }
  });

  it("leaves every other path unowned", () => {
    for (const path of [
      undefined,
      "",
      "/usr/local/bin/php",
      "/opt/Cellar/php",
      "/opt/nix/php",
      "/srv/store/php",
      "/nix/store",
    ]) {
      assert.strictEqual(packageStoreOf(path), undefined, `${path}`);
    }
  });
});
