it("utils.js barrel exports exactly the expected 267 public names", () => {
  const actualNames = Object.keys(barrel).sort();
  const expected = [...EXPECTED_NAMES].sort();
  // Derived from the list rather than repeated as a literal, so the count and
  // the names can never disagree again.
  assert.strictEqual(
    actualNames.length,
    expected.length,
    `barrel must export exactly ${expected.length} names`,
  );
  assert.deepStrictEqual(
    actualNames,
    expected,
    "barrel name set drifted from the committed list",
  );
});

it("accessing every exported name is safe (no TDZ/cycle breakage)", () => {
  // A TDZ or broken-cycle binding throws ReferenceError on access. Some names
  // are legitimately `undefined` when their env vars are unset
  // (CDXGEN_SPDX_CREATED_BY, FETCH_LICENSE), so we check for thrown errors,
  // not for truthy values.
  const broken = [];
  for (const name of Object.keys(barrel)) {
    try {
      // Probing by name is the point: a throwing binding must be reported
      // individually, and static access cannot enumerate the barrel.
      // biome-ignore lint/performance/noDynamicNamespaceImportAccess: see above
      barrel[name];
    } catch {
      broken.push(name);
    }
  }
  assert.deepStrictEqual(
    broken,
    [],
    `these names throw on access: ${broken.join(", ")}`,
  );
});

it("internal names _clearMetadataCache and temporaryFiles are absent from the barrel", () => {
  assert.ok(
    !("_clearMetadataCache" in barrel),
    "_clearMetadataCache must not leak into the barrel",
  );
  assert.ok(
    !("temporaryFiles" in barrel),
    "temporaryFiles must not leak into the barrel",
  );
});
